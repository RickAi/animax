use animax_animation::{
    eval_color, eval_float, eval_gradient, eval_i32, eval_point, eval_position,
    eval_repeater_transform, eval_shape, eval_transform,
};
use animax_base::{lerp_f32, Color};
use animax_model::*;
use animax_property::{LayerPropertyType, PropertyStore};
use animax_skity::{
    Canvas, ColorFilter, FillType, Matrix, Paint, PaintStyle, Path, PathEffect, PathMeasure,
    Shader, StrokeCap, StrokeJoin, TileMode,
};

#[derive(Clone)]
pub struct TrimSpec {
    pub start: f32,
    pub end: f32,
    pub offset: f32,
    pub individually: bool,
}

/// Renders a list of Lottie `ContentModel` items (inside a ShapeLayer or ShapeGroup) onto `canvas`.
pub fn draw_content_items(
    items: &[ContentModel],
    canvas: &mut Canvas,
    parent_matrix: &Matrix,
    parent_alpha: f32,
    frame: f32,
    key_path: &mut Vec<String>,
    props: &PropertyStore,
    inherited_trims: &[TrimSpec],
) {
    // Check for group transform and repeater inside this item list
    let mut group_matrix = *parent_matrix;
    let mut group_alpha = parent_alpha;

    for item in items {
        if let ContentModel::Transform(tr) = item {
            let ev = eval_transform(tr, frame);
            group_matrix.pre_concat(&ev.matrix);
            group_alpha *= (ev.opacity as f32) / 100.0;
        }
    }

    if group_alpha <= 0.0 {
        return;
    }

    // Handle Repeater if present in this group
    if let Some((rp_idx, repeater)) = items.iter().enumerate().find_map(|(i, it)| {
        if let ContentModel::Repeater(rp) = it {
            if !rp.hidden {
                return Some((i, rp));
            }
        }
        None
    }) {
        let copies = eval_float(&repeater.copies, frame, 1.0).max(0.0);
        let offset = eval_float(&repeater.offset, frame, 0.0);
        let start_op = repeater
            .transform
            .start_opacity
            .as_ref()
            .map_or(100.0, |v| eval_float(v, frame, 100.0))
            / 100.0;
        let end_op = repeater
            .transform
            .end_opacity
            .as_ref()
            .map_or(100.0, |v| eval_float(v, frame, 100.0))
            / 100.0;
        let count = copies.ceil() as i32;
        let sub_items = &items[..rp_idx];
        for i in (0..count).rev() {
            let idx_f = i as f32;
            let mut copy_mat = group_matrix;
            let rp_mat = eval_repeater_transform(&repeater.transform, frame, idx_f + offset);
            copy_mat.pre_concat(&rp_mat);
            let frac = if copies > 1.0 {
                idx_f / copies
            } else {
                0.0
            };
            let copy_alpha = group_alpha * lerp_f32(start_op, end_op, frac);
            draw_content_items(
                sub_items,
                canvas,
                &copy_mat,
                copy_alpha,
                frame,
                key_path,
                props,
                inherited_trims,
            );
        }
        return;
    }

    // Collect TrimPath & RoundedCorners modifiers active at this scope
    let mut trims: Vec<TrimSpec> = inherited_trims.to_vec();
    let mut rounded_radius = 0.0f32;
    for item in items {
        match item {
            ContentModel::TrimPath(tm) if !tm.hidden => {
                trims.push(TrimSpec {
                    start: eval_float(&tm.start, frame, 0.0),
                    end: eval_float(&tm.end, frame, 100.0),
                    offset: eval_float(&tm.offset, frame, 0.0),
                    individually: tm.trim_type == TrimPathType::Individually,
                });
            }
            ContentModel::RoundedCorners(rd) if !rd.hidden => {
                rounded_radius = rounded_radius.max(eval_float(&rd.corner_radius, frame, 0.0));
            }
            _ => {}
        }
    }

    // Collect geometry paths generated by sibling shapes in this group
    let mut group_paths: Vec<Path> = Vec::new();

    // Lottie renders items in reverse order (bottom to top), while geometry precedes fills/strokes.
    for item in items {
        match item {
            ContentModel::Rectangle(rc) if !rc.hidden => {
                key_path.push(rc.name.clone());
                let mut size = eval_point(&rc.size, frame, PointF::default());
                let pos = eval_position(&rc.position, frame);
                let mut radius = eval_float(&rc.corner_radius, frame, 0.0).max(rounded_radius);
                let path_refs: Vec<&str> = key_path.iter().map(|s| s.as_str()).collect();
                if let Some(ov) = props
                    .resolve(&path_refs, LayerPropertyType::RectangleSize, frame.round() as i32)
                    .and_then(|v| v.as_point())
                {
                    size = ov;
                }
                if let Some(ov) = props
                    .resolve(&path_refs, LayerPropertyType::CornerRadius, frame.round() as i32)
                    .and_then(|v| v.as_f32())
                {
                    radius = ov;
                }
                let half_w = size.x * 0.5;
                let half_h = size.y * 0.5;
                let rect = RectF::new(pos.x - half_w, pos.y - half_h, pos.x + half_w, pos.y + half_h);
                let mut p = Path::new();
                p.add_rounded_rect(rect, radius, radius);
                group_paths.push(p);
                key_path.pop();
            }
            ContentModel::Ellipse(el) if !el.hidden => {
                key_path.push(el.name.clone());
                let mut size = eval_point(&el.size, frame, PointF::default());
                let pos = eval_position(&el.position, frame);
                let path_refs: Vec<&str> = key_path.iter().map(|s| s.as_str()).collect();
                if let Some(ov) = props
                    .resolve(&path_refs, LayerPropertyType::EllipseSize, frame.round() as i32)
                    .and_then(|v| v.as_point())
                {
                    size = ov;
                }
                let half_w = size.x * 0.5;
                let half_h = size.y * 0.5;
                let mut p = Path::new();
                p.add_oval(RectF::new(
                    pos.x - half_w,
                    pos.y - half_h,
                    pos.x + half_w,
                    pos.y + half_h,
                ));
                group_paths.push(p);
                key_path.pop();
            }
            ContentModel::Polystar(sr) if !sr.hidden => {
                key_path.push(sr.name.clone());
                group_paths.push(build_polystar_path(sr, frame));
                key_path.pop();
            }
            ContentModel::ShapePath(sh) if !sh.hidden => {
                key_path.push(sh.name.clone());
                let shape_data = eval_shape(&sh.shape, frame);
                let p = Path::from_shape_data(&shape_data);
                if !p.is_empty() {
                    group_paths.push(p);
                }
                key_path.pop();
            }
            _ => {}
        }
    }

    // Build combined path with any TrimPath applied
    let combined_path = build_combined_path(&group_paths, &trims);

    // Draw child groups and paints in reverse Lottie stack order
    for item in items.iter().rev() {
        match item {
            ContentModel::ShapeGroup(gr) if !gr.hidden => {
                key_path.push(gr.name.clone());
                draw_content_items(
                    &gr.items,
                    canvas,
                    &group_matrix,
                    group_alpha,
                    frame,
                    key_path,
                    props,
                    &trims,
                );
                key_path.pop();
            }
            ContentModel::ShapeFill(fl) if !fl.hidden && fl.fill_enabled => {
                if combined_path.is_empty() {
                    continue;
                }
                key_path.push(fl.name.clone());
                let path_refs: Vec<&str> = key_path.iter().map(|s| s.as_str()).collect();
                let mut color = fl
                    .color
                    .as_ref()
                    .map_or(Color::BLACK, |c| eval_color(c, frame, Color::BLACK));
                if let Some(ov) = props
                    .resolve(&path_refs, LayerPropertyType::Color, frame.round() as i32)
                    .and_then(|v| v.as_color())
                {
                    color = ov;
                }
                let mut opacity = fl
                    .opacity
                    .as_ref()
                    .map_or(100, |o| eval_i32(o, frame, 100));
                if let Some(ov) = props
                    .resolve(&path_refs, LayerPropertyType::Opacity, frame.round() as i32)
                    .and_then(|v| v.as_i32())
                {
                    opacity = ov;
                }
                let final_alpha =
                    (group_alpha * (opacity.clamp(0, 100) as f32 / 100.0) * (color.a as f32 / 255.0))
                        .clamp(0.0, 1.0);
                color.a = (final_alpha * 255.0).round() as u8;

                let mut paint = Paint::default();
                paint.style = PaintStyle::Fill;
                paint.color = color;
                apply_color_filter_override(&mut paint, &path_refs, props, frame);

                let mut draw_path = combined_path.clone();
                draw_path.fill_type = to_fill_type(fl.fill_rule);

                canvas.save();
                canvas.set_matrix(group_matrix);
                canvas.draw_path(&draw_path, &paint);
                canvas.restore();
                key_path.pop();
            }
            ContentModel::ShapeStroke(st) if !st.hidden => {
                if combined_path.is_empty() {
                    continue;
                }
                key_path.push(st.name.clone());
                let path_refs: Vec<&str> = key_path.iter().map(|s| s.as_str()).collect();
                let mut color = eval_color(&st.color, frame, Color::BLACK);
                if let Some(ov) = props
                    .resolve(&path_refs, LayerPropertyType::StrokeColor, frame.round() as i32)
                    .or_else(|| props.resolve(&path_refs, LayerPropertyType::Color, frame.round() as i32))
                    .and_then(|v| v.as_color())
                {
                    color = ov;
                }
                let opacity = props
                    .resolve(&path_refs, LayerPropertyType::Opacity, frame.round() as i32)
                    .and_then(|v| v.as_i32())
                    .unwrap_or_else(|| eval_i32(&st.opacity, frame, 100));
                let width = props
                    .resolve(&path_refs, LayerPropertyType::StrokeWidth, frame.round() as i32)
                    .and_then(|v| v.as_f32())
                    .unwrap_or_else(|| eval_float(&st.width, frame, 1.0));

                if width > 0.0 {
                    let final_alpha = (group_alpha
                        * (opacity.clamp(0, 100) as f32 / 100.0)
                        * (color.a as f32 / 255.0))
                        .clamp(0.0, 1.0);
                    color.a = (final_alpha * 255.0).round() as u8;

                    let mut paint = Paint::default();
                    paint.style = PaintStyle::Stroke;
                    paint.color = color;
                    paint.stroke_width = width;
                    paint.stroke_cap = to_stroke_cap(st.cap_type);
                    paint.stroke_join = to_stroke_join(st.join_type);
                    paint.stroke_miter = st.miter_limit;
                    paint.path_effect = build_dash_effect(&st.dash_pattern, st.dash_offset.as_ref(), frame);
                    apply_color_filter_override(&mut paint, &path_refs, props, frame);

                    canvas.save();
                    canvas.set_matrix(group_matrix);
                    canvas.draw_path(&combined_path, &paint);
                    canvas.restore();
                }
                key_path.pop();
            }
            ContentModel::GradientFill(gf) if !gf.hidden => {
                if combined_path.is_empty() {
                    continue;
                }
                key_path.push(gf.name.clone());
                let opacity = eval_i32(&gf.opacity, frame, 100).clamp(0, 100) as f32 / 100.0;
                let shader = build_gradient_shader(
                    gf.gradient_type,
                    &gf.gradient_color,
                    &gf.start_point,
                    &gf.end_point,
                    frame,
                );
                let mut paint = Paint::default();
                paint.style = PaintStyle::Fill;
                paint.color = Color::WHITE;
                paint.set_alpha_f(group_alpha * opacity);
                paint.shader = Some(shader);

                let mut draw_path = combined_path.clone();
                draw_path.fill_type = to_fill_type(gf.fill_rule);

                canvas.save();
                canvas.set_matrix(group_matrix);
                canvas.draw_path(&draw_path, &paint);
                canvas.restore();
                key_path.pop();
            }
            ContentModel::GradientStroke(gs) if !gs.hidden => {
                if combined_path.is_empty() {
                    continue;
                }
                key_path.push(gs.name.clone());
                let width = eval_float(&gs.width, frame, 1.0);
                if width > 0.0 {
                    let opacity = eval_i32(&gs.opacity, frame, 100).clamp(0, 100) as f32 / 100.0;
                    let shader = build_gradient_shader(
                        gs.gradient_type,
                        &gs.gradient_color,
                        &gs.start_point,
                        &gs.end_point,
                        frame,
                    );
                    let mut paint = Paint::default();
                    paint.style = PaintStyle::Stroke;
                    paint.color = Color::WHITE;
                    paint.set_alpha_f(group_alpha * opacity);
                    paint.stroke_width = width;
                    paint.stroke_cap = to_stroke_cap(gs.cap_type);
                    paint.stroke_join = to_stroke_join(gs.join_type);
                    paint.stroke_miter = gs.miter_limit;
                    paint.path_effect = build_dash_effect(&gs.dash_pattern, gs.dash_offset.as_ref(), frame);
                    paint.shader = Some(shader);

                    canvas.save();
                    canvas.set_matrix(group_matrix);
                    canvas.draw_path(&combined_path, &paint);
                    canvas.restore();
                }
                key_path.pop();
            }
            _ => {}
        }
    }
}

/// Computes the bounding box of content items in local coordinates (used for bounds & hit testing).
pub fn compute_content_bounds(items: &[ContentModel], frame: f32) -> RectF {
    let mut bounds = RectF::default();
    let mut group_mat = Matrix::identity();
    for item in items {
        if let ContentModel::Transform(tr) = item {
            group_mat.pre_concat(&eval_transform(tr, frame).matrix);
        }
    }
    for item in items {
        match item {
            ContentModel::ShapeGroup(gr) if !gr.hidden => {
                let sub = compute_content_bounds(&gr.items, frame);
                if !sub.is_empty() {
                    bounds.union(&group_mat.map_rect(sub));
                }
            }
            ContentModel::Rectangle(rc) if !rc.hidden => {
                let size = eval_point(&rc.size, frame, PointF::default());
                let pos = eval_position(&rc.position, frame);
                let r = RectF::new(
                    pos.x - size.x * 0.5,
                    pos.y - size.y * 0.5,
                    pos.x + size.x * 0.5,
                    pos.y + size.y * 0.5,
                );
                bounds.union(&group_mat.map_rect(r));
            }
            ContentModel::Ellipse(el) if !el.hidden => {
                let size = eval_point(&el.size, frame, PointF::default());
                let pos = eval_position(&el.position, frame);
                let r = RectF::new(
                    pos.x - size.x * 0.5,
                    pos.y - size.y * 0.5,
                    pos.x + size.x * 0.5,
                    pos.y + size.y * 0.5,
                );
                bounds.union(&group_mat.map_rect(r));
            }
            ContentModel::Polystar(sr) if !sr.hidden => {
                let b = build_polystar_path(sr, frame).bounds();
                if !b.is_empty() {
                    bounds.union(&group_mat.map_rect(b));
                }
            }
            ContentModel::ShapePath(sh) if !sh.hidden => {
                let b = Path::from_shape_data(&eval_shape(&sh.shape, frame)).bounds();
                if !b.is_empty() {
                    bounds.union(&group_mat.map_rect(b));
                }
            }
            _ => {}
        }
    }
    bounds
}

fn build_combined_path(paths: &[Path], trims: &[TrimSpec]) -> Path {
    let mut combined = Path::new();
    if paths.is_empty() {
        return combined;
    }
    if trims.is_empty() {
        for p in paths {
            combined.add_path(p);
        }
        return combined;
    }
    // Apply trims
    let mut current_paths = paths.to_vec();
    for tm in trims {
        if tm.individually {
            let mut next = Path::new();
            for p in &current_paths {
                apply_trim_to_path(p, tm, &mut next);
            }
            current_paths = vec![next];
        } else {
            let mut merged = Path::new();
            for p in &current_paths {
                merged.add_path(p);
            }
            let mut trimmed = Path::new();
            apply_trim_to_path(&merged, tm, &mut trimmed);
            current_paths = vec![trimmed];
        }
    }
    for p in current_paths {
        combined.add_path(&p);
    }
    combined
}

fn apply_trim_to_path(src: &Path, tm: &TrimSpec, dst: &mut Path) {
    let mut start_pct = (tm.start / 100.0).clamp(0.0, 1.0);
    let mut end_pct = (tm.end / 100.0).clamp(0.0, 1.0);
    if start_pct > end_pct {
        std::mem::swap(&mut start_pct, &mut end_pct);
    }
    if (end_pct - start_pct).abs() < 1e-5 {
        return;
    }
    let offset = (tm.offset % 360.0) / 360.0;
    let mut s = (start_pct + offset).rem_euclid(1.0);
    let mut e = (end_pct + offset).rem_euclid(1.0);
    if (end_pct - start_pct) >= 0.9999 {
        dst.add_path(src);
        return;
    }

    let mut pm = PathMeasure::from_path(src, false);
    loop {
        let len = pm.length();
        if len > 0.0 {
            if s < e {
                pm.get_segment(s * len, e * len, dst, true);
            } else {
                pm.get_segment(s * len, len, dst, true);
                pm.get_segment(0.0, e * len, dst, true);
            }
        }
        if !pm.next_contour() {
            break;
        }
    }
    let _ = (&mut s, &mut e);
}

fn build_polystar_path(sr: &PolystarShapeModel, frame: f32) -> Path {
    let points = eval_float(&sr.points, frame, 5.0).max(3.0);
    let pos = eval_position(&sr.position, frame);
    let rotation = eval_float(&sr.rotation, frame, 0.0) - 90.0;
    let outer_r = eval_float(&sr.outer_radius, frame, 0.0);
    let inner_r = sr
        .inner_radius
        .as_ref()
        .map_or(outer_r * 0.5, |r| eval_float(r, frame, outer_r * 0.5));

    let num_points = points.floor() as usize;
    let mut path = Path::new();
    if num_points < 3 || outer_r <= 0.0 {
        return path;
    }

    let mut angle = rotation.to_radians();
    let step = std::f32::consts::TAU / (num_points as f32);

    match sr.polystar_type {
        PolystarType::Polygon => {
            for i in 0..num_points {
                let x = pos.x + outer_r * angle.cos();
                let y = pos.y + outer_r * angle.sin();
                if i == 0 {
                    path.move_to(x, y);
                } else {
                    path.line_to(x, y);
                }
                angle += step;
            }
            path.close();
        }
        PolystarType::Star => {
            let half_step = step * 0.5;
            for i in 0..num_points {
                let ox = pos.x + outer_r * angle.cos();
                let oy = pos.y + outer_r * angle.sin();
                if i == 0 {
                    path.move_to(ox, oy);
                } else {
                    path.line_to(ox, oy);
                }
                let mid_angle = angle + half_step;
                let ix = pos.x + inner_r * mid_angle.cos();
                let iy = pos.y + inner_r * mid_angle.sin();
                path.line_to(ix, iy);
                angle += step;
            }
            path.close();
        }
    }
    path
}

fn build_gradient_shader(
    gtype: GradientType,
    gc: &AnimatableGradient,
    start_pt: &AnimatablePoint,
    end_pt: &AnimatablePoint,
    frame: f32,
) -> Shader {
    let grad = eval_gradient(gc, frame);
    let s = eval_point(start_pt, frame, PointF::default());
    let e = eval_point(end_pt, frame, PointF::new(100.0, 0.0));
    let colors: Vec<Color> = grad.colors.iter().map(|&c| Color::from_i32(c)).collect();
    let positions = grad.positions;

    match gtype {
        GradientType::Radial => {
            let radius = (e.x - s.x).hypot(e.y - s.y).max(0.001);
            Shader::RadialGradient {
                center: s,
                radius,
                colors,
                positions,
                tile_mode: TileMode::Clamp,
            }
        }
        GradientType::Linear | GradientType::Conic => Shader::LinearGradient {
            start: s,
            end: e,
            colors,
            positions,
            tile_mode: TileMode::Clamp,
        },
    }
}

fn build_dash_effect(
    pattern: &[AnimatableFloat],
    offset: Option<&AnimatableFloat>,
    frame: f32,
) -> Option<PathEffect> {
    if pattern.is_empty() {
        return None;
    }
    let mut intervals: Vec<f32> = pattern
        .iter()
        .map(|p| eval_float(p, frame, 0.0).max(0.0))
        .collect();
    if intervals.len() % 2 == 1 {
        let first = intervals[0];
        intervals.push(first);
    }
    let phase = offset.map_or(0.0, |o| eval_float(o, frame, 0.0));
    Some(PathEffect::Dash { intervals, phase })
}

fn apply_color_filter_override(
    paint: &mut Paint,
    path: &[&str],
    props: &PropertyStore,
    frame: f32,
) {
    if let Some(p) = props.resolve(path, LayerPropertyType::ColorFilter, frame.round() as i32) {
        if let animax_property::ValueParamData::ColorFilter(cf) = p.data {
            paint.color_filter = Some(ColorFilter {
                color: Color::from_i32(cf.color),
                mode: BlendMode::from_i32(cf.mode),
            });
        }
    }
}

fn to_fill_type(r: FillRule) -> FillType {
    match r {
        FillRule::EvenOdd => FillType::EvenOdd,
        FillRule::Winding => FillType::Winding,
    }
}

fn to_stroke_cap(c: LineCapType) -> StrokeCap {
    match c {
        LineCapType::Round => StrokeCap::Round,
        LineCapType::Square => StrokeCap::Square,
        LineCapType::Butt => StrokeCap::Butt,
    }
}

fn to_stroke_join(j: LineJoinType) -> StrokeJoin {
    match j {
        LineJoinType::Round => StrokeJoin::Round,
        LineJoinType::Bevel => StrokeJoin::Bevel,
        LineJoinType::Miter => StrokeJoin::Miter,
    }
}
